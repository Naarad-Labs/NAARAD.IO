// node --test tests/
// Tests the sitemap checker against fixtures in a temp directory
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync, existsSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { check, parseSitemap, findBuiltPages, isNoindex } from '../scripts/check-sitemap.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCRIPT = path.join(ROOT, 'scripts', 'check-sitemap.mjs');
const MARKER = 'Generated by scripts/build-site.mjs';

const createTempDir = () => mkdtempSync(path.join(tmpdir(), 'sitemap-test-'));

const createSitemap = (dir, urls) => {
  const sitemapContent = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(url => `  <url><loc>${url}</loc></url>`).join('\n')}
</urlset>`;
  writeFileSync(path.join(dir, 'sitemap.xml'), sitemapContent);
};

const createHtmlFile = (dir, filename, content = '') => {
  const fullContent = `<!DOCTYPE html>
<html>
<head><title>${filename}</title></head>
<body>
${content}
<!-- ${MARKER} -->
</body>
</html>`;
  const filePath = path.join(dir, filename);
  const dirPath = path.dirname(filePath);
  if (!existsSync(dirPath)) {
    mkdirSync(dirPath, { recursive: true });
  }
  writeFileSync(filePath, fullContent);
};

const runScript = (args = [], tempDir) => {
  return spawnSync(process.execPath, [SCRIPT, '--root', tempDir, ...args], { encoding: 'utf8' });
};

test('clean fixture returns no problems', () => {
  const tempDir = createTempDir();
  try {
    // Create sitemap with two pages
    createSitemap(tempDir, ['https://example.com/', 'https://example.com/about']);
    
    // Create corresponding HTML files
    createHtmlFile(tempDir, 'index.html');
    createHtmlFile(tempDir, 'about/index.html');
    
    const result = runScript([], tempDir);
    assert.equal(result.status, 0, result.stdout + result.stderr);
    assert.match(result.stdout, /No problems found/);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

test('missing-from-sitemap rule triggers when a built page is not in sitemap', () => {
  const tempDir = createTempDir();
  try {
    // Create sitemap with only one page
    createSitemap(tempDir, ['https://example.com/']);
    
    // Create HTML files
    createHtmlFile(tempDir, 'index.html');
    createHtmlFile(tempDir, 'contact/index.html'); // This page is missing from sitemap
    
    const result = runScript([], tempDir);
    assert.equal(result.status, 1, result.stdout + result.stderr);
    assert.match(result.stdout, /\[missing-from-sitemap\] /);
    assert.match(result.stdout, /built page not in sitemap: \/contact/);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

test('sitemap-orphan rule triggers when sitemap has entry with no built page', () => {
  const tempDir = createTempDir();
  try {
    // Create sitemap with a page that doesn't exist
    createSitemap(tempDir, ['https://example.com/', 'https://example.com/nonexistent']);
    
    // Create only the index.html file
    createHtmlFile(tempDir, 'index.html');
    
    const result = runScript([], tempDir);
    assert.equal(result.status, 1, result.stdout + result.stderr);
    assert.match(result.stdout, /\[sitemap-orphan\] /);
    assert.match(result.stdout, /sitemap entry has no built page: \/nonexistent/);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

test('noindex pages are excluded from sitemap check', () => {
  const tempDir = createTempDir();
  try {
    // Create sitemap with two pages
    createSitemap(tempDir, ['https://example.com/', 'https://example.com/about']);
    
    // Create HTML files, one with noindex
    createHtmlFile(tempDir, 'index.html');
    createHtmlFile(tempDir, 'about/index.html', '<meta name="robots" content="noindex">');
    // The noindex page needs no sitemap line, so the sitemap lists only the home page.
    createSitemap(tempDir, ['https://example.com/']);
    
    const result = runScript([], tempDir);
    assert.equal(result.status, 0, result.stdout + result.stderr);
    assert.match(result.stdout, /No problems found/);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

test('missing sitemap.xml file reports missing-sitemap error', () => {
  const tempDir = createTempDir();
  try {
    // Don't create sitemap.xml
    createHtmlFile(tempDir, 'index.html');
    
    const result = runScript([], tempDir);
    assert.equal(result.status, 1, result.stdout + result.stderr);
    assert.match(result.stdout, /\[missing-sitemap\] /);
    assert.match(result.stdout, /sitemap.xml not found/);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

test('main() returns exit code 2 for bad arguments', () => {
  const tempDir = createTempDir();
  try {
    createSitemap(tempDir, ['https://example.com/']);
    createHtmlFile(tempDir, 'index.html');
    
    // Test unknown option
    assert.equal(runScript(['--unknown'], tempDir).status, 2);
    
    // Test missing root directory
    assert.equal(runScript(['--root'], tempDir).status, 2);
    
    // Test non-existent root directory
    assert.equal(runScript(['--root', '/no/such/dir'], tempDir).status, 2);
    
    // Test invalid root directory (file instead of directory)
    const file = path.join(tempDir, 'not-a-dir');
    writeFileSync(file, 'not a directory');
    assert.equal(runScript(['--root', file], tempDir).status, 2);
    
    // Test help option
    const help = runScript(['--help'], tempDir);
    assert.equal(help.status, 0);
    assert.match(help.stdout, /Usage:/);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

// Test the exported functions directly
test('a noindex page that is listed in the sitemap is reported as sitemap-orphan', () => {
  const tempDir = createTempDir();
  try {
    createSitemap(tempDir, ['https://example.com/', 'https://example.com/about']);
    createHtmlFile(tempDir, 'index.html');
    createHtmlFile(tempDir, 'about/index.html', '<meta name="robots" content="noindex">');

    const result = runScript([], tempDir);
    assert.equal(result.status, 1, result.stdout + result.stderr);
    assert.match(result.stdout, /sitemap-orphan/);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

test('parseSitemap function works correctly', () => {
  const tempDir = createTempDir();
  try {
    createSitemap(tempDir, [
      'https://example.com/',
      'https://example.com/about',
      'https://example.com/contact'
    ]);
    
    const urls = parseSitemap(path.join(tempDir, 'sitemap.xml'));
    assert.deepEqual(urls.sort(), [
      'https://example.com/',
      'https://example.com/about',
      'https://example.com/contact'
    ]);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

test('isNoindex function works correctly', () => {
  const tempDir = createTempDir();
  try {
    // Create HTML files with and without noindex
    createHtmlFile(tempDir, 'normal.html');
    createHtmlFile(tempDir, 'noindex.html', '<meta name="robots" content="noindex">');
    createHtmlFile(tempDir, 'noindex2.html', '<meta name="robots" content="noindex, nofollow">');
    
    // Test the isNoindex function directly
    assert.equal(isNoindex(path.join(tempDir, 'normal.html')), false);
    assert.equal(isNoindex(path.join(tempDir, 'noindex.html')), true);
    assert.equal(isNoindex(path.join(tempDir, 'noindex2.html')), true);
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});

test('findBuiltPages function works correctly', () => {
  const tempDir = createTempDir();
  try {
    // Create HTML files with marker
    createHtmlFile(tempDir, 'index.html');
    createHtmlFile(tempDir, 'about/index.html');
    createHtmlFile(tempDir, '404.html'); // Should be skipped
    createHtmlFile(tempDir, 'nested/deep/page.html');
    
    const pages = findBuiltPages(tempDir);
    
    // Should have 3 pages (404 is skipped)
    assert.equal(pages.length, 3);
    
    // Check index page
    const indexPage = pages.find(p => p.address === '/');
    assert.ok(indexPage, 'Index page not found');
    
    // Check about page
    const aboutPage = pages.find(p => p.address === '/about/');
    assert.ok(aboutPage, 'About page not found');
    
    // Check nested page
    const nestedPage = pages.find(p => p.path.endsWith('nested/deep/page.html'));
    assert.ok(nestedPage, 'Nested page not found');
    // normalPath only folds index.html into a folder address; any other file keeps its name.
    assert.equal(nestedPage.address, '/nested/deep/page.html');
  } finally {
    rmSync(tempDir, { recursive: true });
  }
});