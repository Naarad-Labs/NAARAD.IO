// node --test tests/
// Tests scripts/check-links.mjs against small fixture trees in a temp directory, never the real repo.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, renameSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { check, extractLinks, main, resolveTarget } from '../scripts/check-links.mjs';

const MARKER = 'Generated by scripts/build-site.mjs';

/* A built page whose body holds the given HTML. */
const page = (body = '') => `<!doctype html><html><head><title>t</title></head><body>${body}<!-- ${MARKER} --></body></html>`;

/* Writes { relativePath: text } into a fresh temp directory and returns its path. */
function makeTree(files) {
  const dir = mkdtempSync(path.join(tmpdir(), 'links-test-'));
  for (const [rel, text] of Object.entries(files)) {
    const file = path.join(dir, rel);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  return dir;
}

function withTree(files, fn) {
  const dir = makeTree(files);
  try {
    return fn(dir);
  } finally {
    rmSync(dir, { recursive: true });
  }
}

const CLEAN = {
  'index.html': page('<a href="/routes/">Routes</a><link href="/app/base.css" rel="stylesheet"><script src="/app/main.js"></script>'),
  'routes/index.html': page('<a href="/routes/hampi/">Hampi</a><a href="../">Home</a><img src="hero.jpg">'),
  'routes/hero.jpg': 'jpg',
  'routes/hampi/index.html': page('<a href="/">Home</a>'),
  'app/base.css': 'body {}',
  'app/main.js': '// main',
};

test('a clean tree returns no problems', () => {
  assert.deepEqual(withTree(CLEAN, (dir) => check(dir)), []);
});

test('a renamed route folder with no redirect fails and names the page and the missing target', () => {
  const dir = makeTree(CLEAN);
  try {
    renameSync(path.join(dir, 'routes/hampi'), path.join(dir, 'routes/hampi-renamed'));
    const problems = check(dir);
    assert.equal(problems.length, 1);
    assert.equal(problems[0].rule, 'broken-link');
    assert.equal(problems[0].file, 'routes/index.html');
    assert.match(problems[0].message, /\/routes\/hampi\//);
    assert.match(problems[0].message, /routes\/hampi\/index\.html/);
  } finally {
    rmSync(dir, { recursive: true });
  }
});

test('a missing src file is reported, and a file at the old address (a redirect page) satisfies the link', () => {
  const broken = withTree({ 'index.html': page('<script src="/app/gone.js"></script>') }, (dir) => check(dir));
  assert.equal(broken.length, 1);
  assert.match(broken[0].message, /app\/gone\.js/);
  const redirected = withTree({
    'index.html': page('<a href="/routes/old/">Old</a>'),
    'routes/old/index.html': page('<meta http-equiv="refresh" content="0; url=/routes/new/">'),
  }, (dir) => check(dir));
  assert.deepEqual(redirected, []);
});

test('external, mailto, tel, data, javascript and fragment-only links are ignored', () => {
  const body = ['https://example.com/x', 'http://example.com/y', '//cdn.example.com/z.js', 'mailto:a@example.com',
    'tel:+911234', 'data:image/png;base64,AAAA', 'javascript:void(0)', '#section'].map((href) => `<a href="${href}">x</a>`).join('');
  assert.deepEqual(withTree({ 'index.html': page(body) }, (dir) => check(dir)), []);
});

test('a query string and a fragment are dropped before the file is looked up', () => {
  const files = { 'index.html': page('<a href="/routes/?sport=walk#top">r</a>'), 'routes/index.html': page() };
  assert.deepEqual(withTree(files, (dir) => check(dir)), []);
});

test('a link that climbs out of the tree is broken, even if a file exists there', () => {
  const problems = withTree({ 'routes/index.html': page('<a href="../../../etc/hosts">x</a>') }, (dir) => check(dir));
  assert.equal(problems.length, 1);
  assert.equal(problems[0].rule, 'broken-link');
});

test('a link a page repeats is reported once for that page', () => {
  const problems = withTree({ 'index.html': page('<a href="/nope/">a</a><a href="/nope/">b</a>') }, (dir) => check(dir));
  assert.equal(problems.length, 1);
});

test('files without the build marker and 404.html are not crawled', () => {
  const files = {
    'index.html': page(),
    'draft/index.html': '<a href="/missing/">x</a>',
    '404.html': page('<a href="/also-missing/">x</a>'),
  };
  assert.deepEqual(withTree(files, (dir) => check(dir)), []);
});

test('resolveTarget maps addresses to repo-relative files and returns null for ignored values', () => {
  assert.equal(resolveTarget('index.html', '/'), 'index.html');
  assert.equal(resolveTarget('index.html', '/routes/'), 'routes/index.html');
  assert.equal(resolveTarget('routes/index.html', '../'), 'index.html');
  assert.equal(resolveTarget('routes/hampi/index.html', 'map.js'), 'routes/hampi/map.js');
  assert.equal(resolveTarget('index.html', '/app/main.js?v=3#x'), 'app/main.js');
  assert.equal(resolveTarget('index.html', '/routes'), 'routes/index.html');
  assert.equal(resolveTarget('index.html', 'https://example.com/'), null);
  assert.equal(resolveTarget('index.html', '#top'), null);
  assert.equal(resolveTarget('index.html', ''), null);
});

test('extractLinks reads href and src in single and double quotes', () => {
  assert.deepEqual(extractLinks(`<a href="/a/">x</a><img src='/b.png'><link HREF="/c.css">`), ['/a/', '/b.png', '/c.css']);
});

test('main() returns 0 clean, 1 with problems printed, and 2 for bad arguments', () => {
  const clean = makeTree(CLEAN);
  const broken = makeTree({ 'index.html': page('<a href="/nope/">x</a>') });
  try {
    const out = [];
    const io = { out: (s) => out.push(s), err: () => {} };
    assert.equal(main(['--root', clean], io), 0);
    assert.match(out.join(' '), /No problems found/);
    out.length = 0;
    assert.equal(main(['--root', broken], io), 1);
    assert.match(out.join(' '), /\[broken-link\] index\.html: \/nope\//);
    assert.match(out.join(' '), /1 problem found/);
    assert.equal(main(['--bogus'], io), 2);
    assert.equal(main(['--root'], io), 2);
    assert.equal(main(['stray'], io), 2);
    assert.equal(main(['--root', path.join(clean, 'nope')], io), 2);
    assert.equal(main(['--help'], io), 0);
  } finally {
    rmSync(clean, { recursive: true });
    rmSync(broken, { recursive: true });
  }
});
