// node --test tests/
// Tests scripts/check-page-meta.mjs against small fixture trees in a temp directory, never the real repo.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { check, canonicalIsElsewhere, main, pageMeta } from '../scripts/check-page-meta.mjs';

const MARKER = 'Generated by scripts/build-site.mjs';

/* A built page's HTML. head holds any extra head tags; the defaults give a complete, valid head. */
function page({ title = 'A title', description = 'A description', canonical = 'https://example.com/', head = '' } = {}) {
  const parts = [];
  if (title !== null) parts.push(`<title>${title}</title>`);
  if (description !== null) parts.push(`<meta name="description" content="${description}">`);
  if (canonical !== null) parts.push(`<link rel="canonical" href="${canonical}">`);
  return `<!doctype html><html><head>${parts.join('')}${head}</head><body><!-- ${MARKER} --></body></html>`;
}

/* Writes { relativePath: html } into a fresh temp directory and returns its path. */
function makeTree(files) {
  const dir = mkdtempSync(path.join(tmpdir(), 'page-meta-test-'));
  for (const [rel, html] of Object.entries(files)) {
    const file = path.join(dir, rel);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, html);
  }
  return dir;
}

function withTree(files, fn) {
  const dir = makeTree(files);
  try {
    return fn(dir);
  } finally {
    rmSync(dir, { recursive: true });
  }
}

const rules = (problems) => problems.map((problem) => problem.rule);

const CLEAN = {
  'index.html': page(),
  'about/index.html': page({ title: 'About', description: 'About us', canonical: 'https://example.com/about/' }),
};

test('a clean tree returns no problems', () => {
  assert.deepEqual(withTree(CLEAN, (dir) => check(dir)), []);
});

test('two pages with the same title fail as duplicate-title and name both pages', () => {
  const problems = withTree({
    ...CLEAN,
    'about/index.html': page({ title: 'A title', description: 'About us', canonical: 'https://example.com/about/' }),
  }, (dir) => check(dir));
  assert.deepEqual(rules(problems), ['duplicate-title']);
  assert.match(problems[0].message, /index\.html/);
  assert.match(problems[0].message, /about\/index\.html/);
});

test('two pages with the same description fail as duplicate-description', () => {
  const problems = withTree({
    ...CLEAN,
    'about/index.html': page({ title: 'About', description: 'A description', canonical: 'https://example.com/about/' }),
  }, (dir) => check(dir));
  assert.deepEqual(rules(problems), ['duplicate-description']);
});

test('an empty or missing title is empty-title, and a missing description is empty-description', () => {
  const noTitle = withTree({ 'index.html': page({ title: '' }) }, (dir) => check(dir));
  assert.deepEqual(rules(noTitle), ['empty-title']);
  const noDescription = withTree({ 'index.html': page({ description: null }) }, (dir) => check(dir));
  assert.deepEqual(rules(noDescription), ['empty-description']);
});

test('no canonical, two canonicals and a non-https canonical are all canonical-count', () => {
  const none = withTree({ 'index.html': page({ canonical: null }) }, (dir) => check(dir));
  assert.deepEqual(rules(none), ['canonical-count']);
  const two = withTree({ 'index.html': page({ head: '<link rel="canonical" href="https://example.com/x/">' }) }, (dir) => check(dir));
  assert.deepEqual(rules(two), ['canonical-count']);
  const http = withTree({ 'index.html': page({ canonical: 'http://example.com/' }) }, (dir) => check(dir));
  assert.deepEqual(rules(http), ['canonical-count']);
});

test('a page canonical to another page may repeat that page\'s title and description', () => {
  const problems = withTree({
    'routes/index.html': page({ title: 'Routes', description: 'All routes', canonical: 'https://example.com/routes/' }),
    'explore/index.html': page({ title: 'Routes', description: 'All routes', canonical: 'https://example.com/routes/' }),
  }, (dir) => check(dir));
  assert.deepEqual(problems, []);
});

test('a noindex page is not checked and does not count toward duplicates', () => {
  const problems = withTree({
    ...CLEAN,
    'private/index.html': page({ title: 'A title', description: 'A description', head: '<meta name="robots" content="noindex">' }),
  }, (dir) => check(dir));
  assert.deepEqual(problems, []);
});

test('files without the build marker, and 404.html, are ignored', () => {
  const problems = withTree({
    ...CLEAN,
    'draft/index.html': '<html><head><title>A title</title></head></html>',
    '404.html': page({ title: 'A title', description: 'A description' }),
  }, (dir) => check(dir));
  assert.deepEqual(problems, []);
});

test('pageMeta reads attributes in any order and values that contain the other quote character', () => {
  const html = `<link href="https://example.com/a/" rel="canonical">`
    + `<meta content="Hampi's best walk" name="description">`
    + `<title>  Hampi  </title>`;
  assert.deepEqual(pageMeta(html), { canonicals: ['https://example.com/a/'], title: 'Hampi', description: "Hampi's best walk" });
  assert.deepEqual(pageMeta('<html></html>'), { canonicals: [], title: '', description: '' });
});

test('canonicalIsElsewhere compares the canonical path with the file\'s own address', () => {
  assert.equal(canonicalIsElsewhere('https://example.com/routes/', 'explore/index.html'), true);
  assert.equal(canonicalIsElsewhere('https://example.com/routes/', 'routes/index.html'), false);
  assert.equal(canonicalIsElsewhere('https://example.com/', 'index.html'), false);
  assert.equal(canonicalIsElsewhere('not a url', 'index.html'), false);
});

test('main() returns 0 clean, 1 with problems printed, and 2 for bad arguments', () => {
  const clean = makeTree(CLEAN);
  const broken = makeTree({ ...CLEAN, 'about/index.html': page({ title: 'A title', description: 'About us', canonical: 'https://example.com/about/' }) });
  try {
    const out = [];
    const err = [];
    const io = { out: (s) => out.push(s), err: (s) => err.push(s) };
    assert.equal(main(['--root', clean], io), 0);
    assert.match(out.join(' '), /No problems found/);
    out.length = 0;
    assert.equal(main(['--root', broken], io), 1);
    assert.match(out.join(' '), /\[duplicate-title\]/);
    assert.match(out.join(' '), /1 problem found/);
    assert.equal(main(['--bogus'], io), 2);
    assert.equal(main(['--root'], io), 2);
    assert.equal(main(['stray'], io), 2);
    assert.equal(main(['--root', path.join(clean, 'nope')], io), 2);
    assert.equal(main(['--help'], io), 0);
  } finally {
    rmSync(clean, { recursive: true });
    rmSync(broken, { recursive: true });
  }
});
