#!/usr/bin/env node
/* Compare sitemap URLs with pre-rendered routes, stories and static pages.
 *
 *   node scripts/check-sitemap.mjs                    # check the repo above scripts/
 *   node scripts/check-sitemap.mjs --root /path/to/repo  # check another repo
 *
 * Exit code: 0 clean, 1 at least one problem, 2 bad arguments.
 * Zero dependencies, Node 18+.
 *
 * Rules:
 *   missing-from-sitemap  a built page with no sitemap line
 *   sitemap-orphan       a sitemap line with no built page
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ORIGIN, normalPath } from '../app/urls.js';

const MARKER = 'Generated by scripts/build-site.mjs';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Parse sitemap.xml and return an array of URL strings.
 */
export function parseSitemap(sitemapPath) {
  const xml = fs.readFileSync(sitemapPath, 'utf8');
  const locs = [];
  const locRegex = /<loc>([^<]+)<\/loc>/g;
  let match;
  
  while ((match = locRegex.exec(xml)) !== null) {
    locs.push(match[1]);
  }
  
  return locs;
}

/**
 * Find all built pages (HTML files with the marker) and return them as
 * { path: string, url: string, address: string } objects.
 */
export function findBuiltPages(rootDir) {
  const pages = [];
  const htmlFiles = [];
  
  // Find all HTML files with the marker
  const scanDirectory = (dir) => {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        scanDirectory(fullPath);
      } else if (entry.isFile() && entry.name.endsWith('.html')) {
        try {
          const content = fs.readFileSync(fullPath, 'utf8');
          if (content.includes(MARKER)) {
            htmlFiles.push(fullPath);
          }
        } catch {
          // Skip unreadable files
        }
      }
    }
  };
  
  scanDirectory(rootDir);
  
  // Convert file paths to URLs and addresses
  for (const filePath of htmlFiles) {
    const relativePath = path.relative(rootDir, filePath);
    const url = new URL(relativePath, ORIGIN).href;
    
    // Convert file path to address
    let address;
    if (relativePath === 'index.html') {
      address = '/';
    } else {
      address = normalPath('/' + relativePath);
    }
    
    // Skip 404 page
    if (relativePath === '404.html') {
      continue;
    }
    
    pages.push({ path: filePath, url, address });
  }
  
  return pages;
}

/**
 * Check if a page is marked noindex by reading its content.
 */
export function isNoindex(pagePath) {
  try {
    const content = fs.readFileSync(pagePath, 'utf8');
    const robotsMatch = content.match(/<meta[^>]*name=["']robots["'][^>]*content=["'][^"]*noindex[^"]*["'][^>]*>/i);
    return robotsMatch !== null;
  } catch {
    return false;
  }
}

/**
 * Check if a page has a canonical link pointing to a different address.
 */
export function canonicalElsewhere(pagePath, address) {
  try {
    const content = fs.readFileSync(pagePath, 'utf8');
    const canonicalMatch = content.match(/<link[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)["'][^>]*>/i) ||
                           content.match(/<link[^>]*href=["']([^"']+)["'][^>]*rel=["']canonical["'][^>]*>/i);
    if (!canonicalMatch) {
      return false;
    }
    const href = canonicalMatch[1];
    try {
      const canonicalPath = normalPath(new URL(href).pathname);
      return canonicalPath !== address;
    } catch {
      return false;
    }
  } catch {
    return false;
  }
}

/**
 * Main check function: compare sitemap with built pages.
 */
export function check(rootDir, options = {}) {
  const problems = [];
  
  // Read sitemap.xml
  const sitemapPath = path.join(rootDir, 'sitemap.xml');
  if (!fs.existsSync(sitemapPath)) {
    problems.push({
      rule: 'missing-sitemap',
      file: sitemapPath,
      message: 'sitemap.xml not found'
    });
    return problems;
  }
  
  const sitemapUrls = parseSitemap(sitemapPath);
  const builtPages = findBuiltPages(rootDir);
  
  // Create maps for comparison
  const sitemapAddresses = new Set();
  const builtAddresses = new Set();
  
  // Process sitemap URLs - convert to addresses
  for (const url of sitemapUrls) {
    try {
      const parsedUrl = new URL(url);
      const pathname = parsedUrl.pathname;
      const address = normalPath(pathname);
      sitemapAddresses.add(address);
    } catch {
      // Skip invalid URLs
    }
  }
  
  // Process built pages
  for (const page of builtPages) {
    // Skip noindex pages and pages with canonical elsewhere
    if (isNoindex(page.path) || canonicalElsewhere(page.path, page.address)) {
      continue;
    }
    
    builtAddresses.add(page.address);
  }
  
  // Find missing from sitemap
  for (const address of builtAddresses) {
    if (!sitemapAddresses.has(address)) {
      problems.push({
        rule: 'missing-from-sitemap',
        file: address,
        message: `built page not in sitemap: ${address}`
      });
    }
  }
  
  // Find sitemap orphans
  for (const address of sitemapAddresses) {
    if (!builtAddresses.has(address)) {
      problems.push({
        rule: 'sitemap-orphan',
        file: address,
        message: `sitemap entry has no built page: ${address}`
      });
    }
  }
  
  return problems;
}

const USAGE = `Usage: node scripts/check-sitemap.mjs [--root DIR]
  --root DIR   repository root directory (default: the directory above scripts/)`;

export function main(argv, io = { out: (s) => console.log(s), err: (s) => console.error(s) }) {
  let rootDir = ROOT;
  
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--help' || a === '-h') {
      io.out(USAGE);
      return 0;
    }
    if (a === '--root') {
      if (i + 1 >= argv.length) {
        io.err(`--root needs a directory path\n${USAGE}`);
        return 2;
      }
      rootDir = path.resolve(process.cwd(), argv[++i]);
      continue;
    }
    if (a.startsWith('--root=')) {
      rootDir = path.resolve(process.cwd(), a.slice(7));
      continue;
    }
    if (a.startsWith('-')) {
      io.err(`unknown option ${a}\n${USAGE}`);
      return 2;
    }
    io.err(`unexpected argument ${a}\n${USAGE}`);
    return 2;
  }
  
  // Validate root directory
  try {
    const stat = fs.statSync(rootDir);
    if (!stat.isDirectory()) {
      io.err(`not a directory: ${rootDir}`);
      return 2;
    }
  } catch {
    io.err(`directory not found: ${rootDir}`);
    return 2;
  }
  
  const problems = check(rootDir);
  
  if (problems.length === 0) {
    io.out('No problems found');
    return 0;
  }
  
  // Print problems
  for (const problem of problems) {
    io.out(`[${problem.rule}] ${problem.file}: ${problem.message}`);
  }
  
  const summary = `${problems.length} problem${problems.length === 1 ? '' : 's'} found`;
  io.out(summary);
  
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
