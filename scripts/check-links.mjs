#!/usr/bin/env node
/* Crawl the built site and fail on any href or src that does not resolve to a built file.
 *
 *   node scripts/check-links.mjs                    # check the repo above scripts/
 *   node scripts/check-links.mjs --root /path/to/repo  # check another repo
 *
 * Exit code: 0 clean, 1 at least one problem, 2 bad arguments.
 * Zero dependencies, Node 18+.
 *
 * Rules:
 *   broken-link  an href or src that does not resolve to an existing file
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const MARKER = 'Generated by scripts/build-site.mjs';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKIP_DIRS = ['node_modules', '.git', '.claude', 'replica', 'docs', 'test-results'];

/**
 * Find all built pages (HTML files with the marker) and return them as
 * { path: string, relPath: string } objects.
 */
export function findBuiltPages(rootDir) {
  const pages = [];
  
  const scanDirectory = (dir) => {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (SKIP_DIRS.includes(entry.name)) {
          continue;
        }
        scanDirectory(fullPath);
      } else if (entry.isFile() && entry.name.endsWith('.html')) {
        try {
          const content = fs.readFileSync(fullPath, 'utf8');
          if (content.includes(MARKER)) {
            const relPath = path.relative(rootDir, fullPath).replace(/\\/g, '/');
            if (relPath !== '404.html') {
              pages.push({ path: fullPath, relPath });
            }
          }
        } catch {
          // Skip unreadable files
        }
      }
    }
  };
  
  scanDirectory(rootDir);
  
  return pages;
}

/**
 * Resolve a link value from a page to a repo-relative file path, or null if ignored.
 */
export function resolveTarget(pageRelPath, value) {
  // Ignore external, protocol, and fragment-only links
  if (!value ||
      value.startsWith('http:') ||
      value.startsWith('https:') ||
      value.startsWith('//') ||
      value.startsWith('mailto:') ||
      value.startsWith('tel:') ||
      value.startsWith('data:') ||
      value.startsWith('javascript:') ||
      value.startsWith('#')) {
    return null;
  }
  
  // Drop query and fragment
  const cleanValue = value.split('?')[0].split('#')[0];
  
  if (!cleanValue) {
    return null;
  }
  
  // Resolve the path
  let targetPath;
  if (cleanValue.startsWith('/')) {
    // Absolute path from repo root
    targetPath = cleanValue.slice(1);
  } else {
    // Relative to page's folder
    const pageDir = path.posix.dirname(pageRelPath);
    targetPath = path.posix.join(pageDir, cleanValue).replace(/^\.\//, '');
  }
  
  // Map directory paths to index.html
  if (targetPath === '.') {
    targetPath = '';
  }
  if (targetPath.endsWith('/') || targetPath === '') {
    targetPath = targetPath + 'index.html';
  } else if (!path.extname(targetPath)) {
    // No extension, assume it's a directory needing index.html
    targetPath = targetPath + '/index.html';
  }
  
  return targetPath;
}

/**
 * Extract href and src attribute values from HTML content.
 */
export function extractLinks(content) {
  const links = [];
  
  // Match href="..." and src="..." attributes
  const attrRegex = /\b(href|src)\s*=\s*(?:"([^"]*)"|'([^']*)')/gi;
  let match;
  
  while ((match = attrRegex.exec(content)) !== null) {
    const value = match[2] || match[3] || '';
    links.push(value);
  }
  
  return links;
}

/**
 * Main check function: crawl built pages and verify all internal links.
 */
export function check(rootDir, options = {}) {
  const problems = [];
  
  const pages = findBuiltPages(rootDir);
  
  for (const page of pages) {
    let content;
    try {
      content = fs.readFileSync(page.path, 'utf8');
    } catch {
      continue;
    }
    
    // A page that repeats a link is reported once for it.
    for (const value of new Set(extractLinks(content))) {
      const targetRelPath = resolveTarget(page.relPath, value);

      if (targetRelPath === null) {
        continue;
      }

      let isFile = false;
      try {
        const full = path.join(rootDir, targetRelPath);
        // A link that climbs out of the tree (../../x) cannot resolve to a built file.
        isFile = full.startsWith(path.resolve(rootDir) + path.sep) && fs.statSync(full).isFile();
      } catch {
        // missing target: isFile stays false
      }
      if (!isFile) {
        problems.push({
          rule: 'broken-link',
          file: page.relPath,
          message: `${value} -> ${targetRelPath} does not exist`
        });
      }
    }
  }
  
  return problems;
}

const USAGE = `Usage: node scripts/check-links.mjs [--root DIR]
  --root DIR   repository root directory (default: the directory above scripts/)`;

export function main(argv, io = { out: (s) => console.log(s), err: (s) => console.error(s) }) {
  let rootDir = ROOT;
  
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--help' || a === '-h') {
      io.out(USAGE);
      return 0;
    }
    if (a === '--root') {
      if (i + 1 >= argv.length) {
        io.err(`--root needs a directory path\n${USAGE}`);
        return 2;
      }
      rootDir = path.resolve(process.cwd(), argv[++i]);
      continue;
    }
    if (a.startsWith('--root=')) {
      rootDir = path.resolve(process.cwd(), a.slice(7));
      continue;
    }
    if (a.startsWith('-')) {
      io.err(`unknown option ${a}\n${USAGE}`);
      return 2;
    }
    io.err(`unexpected argument ${a}\n${USAGE}`);
    return 2;
  }
  
  // Validate root directory
  try {
    const stat = fs.statSync(rootDir);
    if (!stat.isDirectory()) {
      io.err(`not a directory: ${rootDir}`);
      return 2;
    }
  } catch {
    io.err(`directory not found: ${rootDir}`);
    return 2;
  }
  
  const problems = check(rootDir);
  
  if (problems.length === 0) {
    io.out('No problems found');
    return 0;
  }
  
  // Print problems
  for (const problem of problems) {
    io.out(`[${problem.rule}] ${problem.file}: ${problem.message}`);
  }
  
  const summary = `${problems.length} problem${problems.length === 1 ? '' : 's'} found`;
  io.out(summary);
  
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
