#!/usr/bin/env node
/* Check canonical, title and description on every built page.
 *
 * Rules:
 *   canonical-count      exactly one <link rel="canonical"> with a non-empty https href
 *   empty-title          <title> must not be empty
 *   empty-description    <meta name="description"> must not be empty
 *   duplicate-title      titles must be unique across pages
 *   duplicate-description descriptions must be unique across pages
 *
 * Exit code: 0 clean, 1 at least one problem, 2 bad arguments.
 * Zero dependencies, Node 18+.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const MARKER = 'Generated by scripts/build-site.mjs';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Find all built pages (HTML files with the marker) and return them as
 * { path: string, relative: string } objects.
 * Skips node_modules, .git, .claude, replica, docs, test-results, 404 page.
 */
export function findBuiltPages(rootDir) {
  const pages = [];
  const htmlFiles = [];
  const skipDirs = new Set(['node_modules', '.git', '.claude', 'replica', 'docs', 'test-results']);

  const scanDirectory = (dir) => {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (skipDirs.has(entry.name)) continue;
        scanDirectory(fullPath);
      } else if (entry.isFile() && entry.name.endsWith('.html')) {
        try {
          const content = fs.readFileSync(fullPath, 'utf8');
          if (content.includes(MARKER)) {
            htmlFiles.push(fullPath);
          }
        } catch {
          // Skip unreadable files
        }
      }
    }
  };

  scanDirectory(rootDir);

  for (const filePath of htmlFiles) {
    const relativePath = path.relative(rootDir, filePath);
    if (relativePath === '404.html') continue;
    pages.push({ path: filePath, relative: relativePath.replace(/\\/g, '/') });
  }

  return pages;
}

/** Check if a page is marked noindex by reading its content. */
export function isNoindex(pagePath) {
  try {
    const content = fs.readFileSync(pagePath, 'utf8');
    const robotsMatch = content.match(/<meta[^>]*name=["']robots["'][^>]*content=["'][^"]*noindex[^"]*["'][^>]*>/i);
    return robotsMatch !== null;
  } catch {
    return false;
  }
}

/** Parse a page's HTML and return { canonicals: [hrefs], title, description }.
 *  title and description are trimmed; empty string if missing. */
export function pageMeta(html) {
  // The value of an attribute in one tag, in any attribute order; a quoted value may contain the other quote character.
  const attr = (tag, name) => {
    const m = new RegExp(`\\s${name}\\s*=\\s*(?:"([^"]*)"|'([^']*)')`, 'i').exec(tag);
    return m ? (m[1] ?? m[2]) : null;
  };

  const canonicals = [];
  for (const tag of html.match(/<link\b[^>]*>/gi) || []) {
    if ((attr(tag, 'rel') || '').toLowerCase() === 'canonical') canonicals.push((attr(tag, 'href') || '').trim());
  }

  const titleMatch = html.match(/<title[^>]*>([^<]*)<\/title>/i);
  const title = titleMatch ? titleMatch[1].trim() : '';

  let description = '';
  for (const tag of html.match(/<meta\b[^>]*>/gi) || []) {
    if ((attr(tag, 'name') || '').toLowerCase() === 'description') {
      description = (attr(tag, 'content') || '').trim();
      break;
    }
  }

  return { canonicals, title, description };
}

/** True when a canonical href points at a different page than the file at relativePath ('routes/index.html' is /routes/). */
export function canonicalIsElsewhere(href, relativePath) {
  try {
    const own = '/' + relativePath.replace(/index\.html$/, '');
    const canonical = new URL(href).pathname;
    return canonical !== own && canonical !== own.replace(/\/$/, '');
  } catch {
    return false;
  }
}

/** Main check function: compare built pages for meta correctness. */
export function check(rootDir, options = {}) {
  const problems = [];
  const pages = findBuiltPages(rootDir);

  const titleMap = new Map(); // title -> [relative paths]
  const descMap = new Map();  // description -> [relative paths]

  for (const page of pages) {
    if (isNoindex(page.path)) continue;

    const content = fs.readFileSync(page.path, 'utf8');
    const { canonicals, title, description } = pageMeta(content);

    // Canonical count
    if (canonicals.length !== 1) {
      problems.push({
        rule: 'canonical-count',
        file: page.relative,
        message: `found ${canonicals.length} canonicals`,
      });
    } else {
      const href = canonicals[0];
      if (!href) {
        problems.push({
          rule: 'canonical-count',
          file: page.relative,
          message: 'canonical href is empty',
        });
      } else if (!href.startsWith('https://')) {
        problems.push({
          rule: 'canonical-count',
          file: page.relative,
          message: 'canonical href is not https',
        });
      }
    }

    // Empty title
    if (!title) {
      problems.push({
        rule: 'empty-title',
        file: page.relative,
        message: 'title is empty',
      });
    }

    // Empty description
    if (!description) {
      problems.push({
        rule: 'empty-description',
        file: page.relative,
        message: 'description is empty',
      });
    }

    // A page whose canonical is another page (such as /explore/, canonical to /routes/) repeats that page's
    // title and description on purpose, so it is left out of the uniqueness checks.
    if (canonicals.length === 1 && canonicalIsElsewhere(canonicals[0], page.relative)) continue;

    // Collect for uniqueness checks
    if (title) {
      const list = titleMap.get(title) || [];
      list.push(page.relative);
      titleMap.set(title, list);
    }
    if (description) {
      const list = descMap.get(description) || [];
      list.push(page.relative);
      descMap.set(description, list);
    }
  }

  // Duplicate titles
  for (const [title, list] of titleMap.entries()) {
    if (list.length > 1) {
      problems.push({
        rule: 'duplicate-title',
        file: list[0],
        message: `duplicate title: '${title}' used by: ${list.join(', ')}`,
      });
    }
  }

  // Duplicate descriptions
  for (const [desc, list] of descMap.entries()) {
    if (list.length > 1) {
      problems.push({
        rule: 'duplicate-description',
        file: list[0],
        message: `duplicate description: '${desc}' used by: ${list.join(', ')}`,
      });
    }
  }

  return problems;
}

const USAGE = `Usage: node scripts/check-page-meta.mjs [--root DIR]
  --root DIR   repository root directory (default: the directory above scripts/)`;

export function main(argv, io = { out: (s) => console.log(s), err: (s) => console.error(s) }) {
  let rootDir = ROOT;

  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--help' || a === '-h') {
      io.out(USAGE);
      return 0;
    }
    if (a === '--root') {
      if (i + 1 >= argv.length) {
        io.err(`--root needs a directory path\n${USAGE}`);
        return 2;
      }
      rootDir = path.resolve(process.cwd(), argv[++i]);
      continue;
    }
    if (a.startsWith('--root=')) {
      rootDir = path.resolve(process.cwd(), a.slice(7));
      continue;
    }
    if (a.startsWith('-')) {
      io.err(`unknown option ${a}\n${USAGE}`);
      return 2;
    }
    io.err(`unexpected argument ${a}\n${USAGE}`);
    return 2;
  }

  // Validate root directory
  try {
    const stat = fs.statSync(rootDir);
    if (!stat.isDirectory()) {
      io.err(`not a directory: ${rootDir}`);
      return 2;
    }
  } catch {
    io.err(`directory not found: ${rootDir}`);
    return 2;
  }

  const problems = check(rootDir);

  if (problems.length === 0) {
    io.out('No problems found');
    return 0;
  }

  // Print problems
  for (const problem of problems) {
    io.out(`[${problem.rule}] ${problem.file}: ${problem.message}`);
  }

  const summary = `${problems.length} problem${problems.length === 1 ? '' : 's'} found`;
  io.out(summary);

  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
