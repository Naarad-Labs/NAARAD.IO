#!/usr/bin/env bash
# Everything that must hold before a change is committed or deployed.
#
#   bash scripts/verify.sh
#
# Four stages, each with a banner and a PASS or FAIL line. Stops at the first
# failure and exits non-zero. At the end, prints a timing table for the stages
# that ran.
#
#   1  the build is deterministic and committed: node scripts/build-site.mjs,
#      run twice, gives the same pages, cards, sitemap and lastmod.json both
#      times, and what it gives is what is committed. Commit the generated
#      files with the change that caused them. (While the change is still
#      uncommitted, run with VERIFY_ALLOW_UNCOMMITTED=1 to skip the comparison
#      with the commit.)
#      Run alone (from the repo root): bash -c 'source scripts/verify.sh; check_build'
#   2  node --test tests/: the unit tests, which need nothing but node
#      Run alone (from the repo root): bash -c 'source scripts/verify.sh; check_tests'
#   3  node scripts/check-practical.mjs: the sourced visitor facts in
#      content/practical. Any error fails the step (a value with no source, an
#      API endpoint cited without its method, a figure in the gap notes, stops
#      that are not the route's stops, or a `checked` date more than 180 days
#      old); warnings are allowed
#      Run alone (from the repo root): bash -c 'source scripts/verify.sh; check_practical'
#   4  cd e2e && npx playwright test: the browser checks (needs e2e/node_modules
#      and Chromium)
#      Run alone (from the repo root): bash -c 'source scripts/verify.sh; check_e2e'

MARKER='Generated by scripts/build-site.mjs'

# Every file the build writes: the pages (found by their marker), the sitemap and
# its dates, and the share cards with their credits.
generated() {
  {
    grep -rlF "$MARKER" --include='*.html' \
      --exclude-dir=.git --exclude-dir=node_modules --exclude-dir=.claude --exclude-dir=.agents \
      --exclude-dir=replica --exclude-dir=docs --exclude-dir=test-results .
    echo ./sitemap.xml
    echo ./content/lastmod.json
    find ./Images/og -type f
  } | LC_ALL=C sort -u
}

# One hash for all of them: a file's path and its bytes.
tree_hash() {
  generated | while IFS= read -r file; do printf '%s  %s\n' "$(sha256sum < "$file" | cut -d' ' -f1)" "$file"; done | sha256sum | cut -d' ' -f1
}

# Print a banner, run the command, and on failure print the log tail and exit.
# Usage: step <number> <name> <command...>
step() {
  local num=$1 name=$2
  shift 2
  local log start elapsed
  log=$(mktemp)

  echo "=== stage $num of 4: $name ==="

  start=$SECONDS
  if "$@" >"$log" 2>&1; then
    elapsed=$((SECONDS - start))
    echo "PASS  $name"
    record_timing "$num" "$name" "$elapsed"
  else
    elapsed=$((SECONDS - start))
    echo "FAIL  $name"
    tail -n 40 "$log" | sed 's/^/        /'
    record_timing "$num" "$name" "$elapsed"
    rm -f "$log"
    print_timing_table
    exit 1
  fi
  rm -f "$log"
}

# Record a stage's elapsed seconds for the final table.
record_timing() {
  local num=$1 name=$2 elapsed=$3
  timing_entries+=("stage $num: ${elapsed}s")
  total_seconds=$((total_seconds + elapsed))
}

# Print the timing table (stages that ran, then total).
print_timing_table() {
  if [ ${#timing_entries[@]} -gt 0 ]; then
    echo "=== timing ==="
    for entry in "${timing_entries[@]}"; do
      echo "  $entry"
    done
    echo "  total: ${total_seconds}s"
  fi
}

# The steps run inside `if`, where set -e does not apply, so each command that
# can fail says so with || return.
check_build() {
  local first second
  node scripts/build-site.mjs || return 1
  first=$(tree_hash)
  node scripts/build-site.mjs || return 1
  second=$(tree_hash)
  if [ "$first" != "$second" ]; then
    echo "the second build changed the generated files: the build is not deterministic"
    return 1
  fi
  if [ "${VERIFY_ALLOW_UNCOMMITTED:-}" = 1 ]; then
    echo "generated files not compared with the commit (VERIFY_ALLOW_UNCOMMITTED=1)"
    return 0
  fi
  local stale
  stale=$(generated | xargs git status --porcelain --untracked-files=all -- || true)
  if [ -n "$stale" ]; then
    echo "the generated files differ from the commit; commit them with the change that caused them:"
    echo "$stale"
    return 1
  fi
}

check_tests() {
  node --test --test-reporter=spec tests/*.test.mjs || return 1
}

check_practical() {
  node scripts/check-practical.mjs || return 1
}

check_e2e() {
  if [ ! -d e2e/node_modules/@playwright ]; then
    echo "e2e/node_modules is missing: cd e2e && npm install"
    return 1
  fi
  (cd e2e && npx playwright test) || return 1
}

main() {
  set -euo pipefail
  cd "$(dirname "${BASH_SOURCE[0]}")/.."

  # Timing state (global, reset here so a sourced call starts clean).
  timing_entries=()
  total_seconds=0

  step 1 "build is deterministic and committed  (node scripts/build-site.mjs, twice)" check_build
  step 2 "unit tests                            (node --test tests/)" check_tests
  step 3 "practical facts                       (node scripts/check-practical.mjs)" check_practical
  step 4 "browser checks                        (cd e2e && npx playwright test)" check_e2e

  # All stages passed.
  print_timing_table
  echo "verify: PASS"
}

# Run main only when executed, not when sourced (so the check_* functions can
# be called alone).
if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main
fi
